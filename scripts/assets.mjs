#!/usr/bin/env node
// The asset queue: strategy/campaigns/<campaign>/assets.json. Agents change it only through here.
//
//   node scripts/assets.mjs table  [campaign]                 regenerate asset-plan.md from the queue
//   node scripts/assets.mjs status <id> <status> [note] [--by <name>] [--campaign <c>]
//   node scripts/assets.mjs due    [days=7] [--campaign <c>]  assets releasing soon that aren't approved
//   node scripts/assets.mjs check  [campaign]                 validate every queue (or one)
//   node scripts/assets.mjs show   <id> [--campaign <c>]
//
// Without --campaign, an asset ID is looked up across every campaign. No dependencies.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CAMPAIGNS = path.join(ROOT, "strategy/campaigns");
export const STATUSES = ["planned", "briefed", "drafting", "in-review", "needs-fix",
  "ready-for-approval", "approved", "scheduled", "live", "measured"];
// Only a person moves an asset past review. The script asks for --by and checks the name is an approver.
const HUMAN_GATES = new Set(["approved", "scheduled", "live"]);

// ---- args ------------------------------------------------------------------------------------
const argv = process.argv.slice(2);
function flag(name) {
  const i = argv.indexOf(`--${name}`);
  if (i < 0) return null;
  const v = argv[i + 1];
  argv.splice(i, 2);
  return v;
}
const onlyCampaign = flag("campaign");
const by = flag("by");
const [cmd, ...rest] = argv;

// ---- queue files -----------------------------------------------------------------------------
function queuePaths() {
  return fs.readdirSync(CAMPAIGNS, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(CAMPAIGNS, d.name, "assets.json")))
    .filter((d) => !onlyCampaign || d.name === onlyCampaign)
    .map((d) => path.join(CAMPAIGNS, d.name, "assets.json"));
}
const load = (p) => ({ path: p, data: JSON.parse(fs.readFileSync(p, "utf8")) });
// one asset per line keeps diffs readable: a status change touches one line, not twenty
function save(q) {
  const { assets, footer, ...head } = q.data;
  const lines = Object.entries(head).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  const body = assets.map((a) => "    " + JSON.stringify(a)).join(",\n");
  const out = `{\n${lines.join("\n")}\n  "assets": [\n${body}\n  ],\n  "footer": ${JSON.stringify(footer ?? "")}\n}\n`;
  fs.writeFileSync(q.path, out);
}
function find(id) {
  for (const p of queuePaths()) {
    const q = load(p);
    const a = q.data.assets.find((x) => x.id === id);
    if (a) return { q, a };
  }
  fail(`no asset ${id}${onlyCampaign ? ` in ${onlyCampaign}` : ""}`);
}
function fail(msg) { console.error(msg); process.exit(1); }
const today = () => new Date().toISOString().slice(0, 10);

// ---- formatting ------------------------------------------------------------------------------
const DAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const asDate = (iso) => new Date(`${iso}T12:00:00Z`);
function release(a) {
  if (a.releaseNote) return a.releaseNote;
  if (!a.release) return "To confirm";
  const d = asDate(a.release);
  if (!a.releaseUntil) return `${DAYS[d.getUTCDay()]} ${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]}`;
  const e = asDate(a.releaseUntil);
  return d.getUTCMonth() === e.getUTCMonth()
    ? `${d.getUTCDate()}–${e.getUTCDate()} ${MONTHS[e.getUTCMonth()]}`
    : `${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]}–${e.getUTCDate()} ${MONTHS[e.getUTCMonth()]}`;
}
function statusCell(a) {
  const last = a.history?.at(-1);
  const note = last?.note?.replace(/\s*\(migrated from the plan table\)/, "");
  return note ? `${a.status}: ${note}` : a.status;
}
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|");

// ---- commands --------------------------------------------------------------------------------
function table(q) {
  const d = q.data;
  const rows = d.assets.map((a) => `| ${[a.id, a.title, a.frames, a.channels.join(", "), release(a), a.skill,
    a.folder ? `\`${a.folder.replace(/^content\/[^/]+\//, "")}\`` : "", statusCell(a)].map(cell).join(" | ")} |`);
  const md = [
    `<!-- Generated by scripts/assets.mjs from assets.json. Edit the JSON (or run the script), not this file. -->`,
    `# ${d.title.replace(/\.$/, "")} asset plan`, "", d.intro, "",
    "| ID | Asset | Frames | Channel | Release | Skill | Folder | Status |",
    "|---|---|---|---|---|---|---|---|", ...rows, "", d.footer, "",
  ].join("\n");
  const out = path.join(path.dirname(q.path), "asset-plan.md");
  fs.writeFileSync(out, md);
  console.log(`wrote ${path.relative(ROOT, out)} (${d.assets.length} assets)`);
}

function status(id, next, note) {
  if (!STATUSES.includes(next)) fail(`unknown status "${next}". One of: ${STATUSES.join(", ")}`);
  const { q, a } = find(id);
  if (HUMAN_GATES.has(next)) {
    if (!by) fail(`"${next}" is a person's decision: add --by <name> (one of ${a.approvers.join(", ")})`);
    if (!a.approvers.includes(by) && next === "approved") fail(`${by} is not an approver for ${id} (${a.approvers.join(", ")})`);
    if (next === "approved" && a.status !== "ready-for-approval") fail(`${id} is ${a.status}; only ready-for-approval can be approved`);
  }
  const entry = { date: today(), status: next };
  if (note) entry.note = note;
  if (by) entry.by = by;
  a.status = next;
  (a.history ||= []).push(entry);
  save(q);
  table(q);
  console.log(`${id}: ${next}${note ? ` (${note})` : ""}`);
}

function due(days) {
  const until = new Date(Date.now() + days * 864e5).toISOString().slice(0, 10);
  const open = STATUSES.slice(0, STATUSES.indexOf("approved"));
  const list = queuePaths().flatMap((p) => load(p).data.assets)
    .filter((a) => a.release && a.release <= until && open.includes(a.status))
    .sort((x, y) => x.release.localeCompare(y.release));
  if (!list.length) return console.log(`nothing open releases in the next ${days} days`);
  for (const a of list) {
    const late = a.release < today() ? "  LATE" : "";
    console.log(`${a.release}  ${a.id.padEnd(5)} ${a.status.padEnd(18)} ${a.title}${late}`);
  }
}

function check() {
  let problems = 0;
  const say = (m) => { problems++; console.log(`  ${m}`); };
  for (const p of queuePaths()) {
    const { data } = load(p);
    console.log(path.relative(ROOT, p));
    const ids = new Set();
    for (const a of data.assets) {
      for (const k of ["id", "title", "type", "maker", "status"]) if (!a[k]) say(`${a.id ?? "?"}: missing ${k}`);
      if (ids.has(a.id)) say(`${a.id}: duplicate ID`);
      ids.add(a.id);
      if (!/^A\d+\.\d+$/.test(a.id)) say(`${a.id}: IDs look like A1.6`);
      if (!STATUSES.includes(a.status)) say(`${a.id}: unknown status "${a.status}"`);
      if (!Array.isArray(a.approvers) || !a.approvers.length) say(`${a.id}: no approvers`);
      for (const k of ["release", "releaseUntil"]) if (a[k] && !/^\d{4}-\d{2}-\d{2}$/.test(a[k])) say(`${a.id}: ${k} is not YYYY-MM-DD`);
      if (!a.release && !a.releaseNote) say(`${a.id}: no release date or note`);
      if (a.folder && !fs.existsSync(path.join(ROOT, a.folder))) say(`${a.id}: folder ${a.folder} does not exist`);
      const past = STATUSES.indexOf(a.status) >= STATUSES.indexOf("in-review");
      if (past && !a.folder) say(`${a.id}: is ${a.status} but has no folder`);
      if (past && a.folder && !fs.existsSync(path.join(ROOT, a.folder, "review.md"))) say(`${a.id}: is ${a.status} but has no review.md`);
      if (a.history?.at(-1) && a.history.at(-1).status !== a.status) say(`${a.id}: status ${a.status} but last history entry is ${a.history.at(-1).status}`);
    }
  }
  console.log(problems ? `\n${problems} problem(s)` : "\nOK");
  process.exit(problems ? 1 : 0);
}

switch (cmd) {
  case "table": queuePaths().filter((p) => !rest[0] || p.includes(`/${rest[0]}/`)).forEach((p) => table(load(p))); break;
  case "status": if (rest.length < 2) fail("usage: status <id> <status> [note] [--by <name>]"); status(rest[0], rest[1], rest.slice(2).join(" ")); break;
  case "due": due(Number(rest[0] ?? 7)); break;
  case "check": check(); break;
  case "show": console.log(JSON.stringify(find(rest[0]).a, null, 2)); break;
  default:
    console.error("usage: assets.mjs table|status|due|check|show (see the top of the file)");
    process.exit(2);
}
