"""Dot-matrix map for the homepage closing band (site/dm/dotmap.js).

Samples Natural Earth 1:110m country outlines (public domain) on a regular lon/lat grid
and writes one character per cell: "a" African land, "l" other land, "." sea.
The page draws the dots on a canvas; nothing here is data about Axmed.

Usage:
  python3 scripts/make-dotmap.py <ne_110m_admin_0_countries.geojson> [site/dm/dotmap.js]
"""

import json
import sys
from pathlib import Path

# Frame: Africa with the edges of Europe, the Middle East and South America for context.
LON0, LON1 = -34.0, 70.0
LAT0, LAT1 = -40.0, 44.0
STEP = 1.25  # degrees per dot; about 83 x 67 cells


def rings(geom):
    """Every ring of a Polygon or MultiPolygon as a list of (lon, lat)."""
    polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    return [ring for poly in polys for ring in poly]


def inside(lon, lat, rs):
    """Even-odd test over all rings, so holes (lakes, enclaves) come out as sea."""
    hit = False
    for ring in rs:
        j = len(ring) - 1
        for i in range(len(ring)):
            xi, yi = ring[i]
            xj, yj = ring[j]
            if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
                hit = not hit
            j = i
    return hit


def main():
    src = Path(sys.argv[1])
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "site/dm/dotmap.js")
    feats = json.loads(src.read_text())["features"]
    shapes = []
    for f in feats:
        rs = rings(f["geometry"])
        xs = [p[0] for r in rs for p in r]
        ys = [p[1] for r in rs for p in r]
        box = (min(xs), min(ys), max(xs), max(ys))
        if box[2] < LON0 or box[0] > LON1 or box[3] < LAT0 or box[1] > LAT1:
            continue
        shapes.append((f["properties"]["CONTINENT"] == "Africa", box, rs))

    cols = int((LON1 - LON0) / STEP) + 1
    rows = []
    lat = LAT1
    while lat >= LAT0 - 1e-9:  # north to south, so row 0 is the top of the canvas
        row = []
        for c in range(cols):
            lon = LON0 + c * STEP
            ch = "."
            for africa, (x0, y0, x1, y1), rs in shapes:
                if x0 <= lon <= x1 and y0 <= lat <= y1 and inside(lon, lat, rs):
                    ch = "a" if africa else "l"
                    break
            row.append(ch)
        rows.append("".join(row))
        lat -= STEP

    body = ",\n".join(f'    "{r}"' for r in rows)
    out.write_text(
        "// Generated by scripts/make-dotmap.py from Natural Earth 1:110m (public domain).\n"
        "// a = African land, l = other land, . = sea. Row 0 is the north edge.\n"
        f"window.AX_DOTMAP = {{ lon0: {LON0}, lat1: {LAT1}, step: {STEP}, rows: [\n{body}\n] }};\n"
    )
    print(f"{out}: {cols} x {len(rows)}")


if __name__ == "__main__":
    main()
