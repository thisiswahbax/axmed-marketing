"""Generate brand/tokens.css and brand/tokens.json from brand/system.css.

brand/system.css is the one source of truth for colour, type and motion, shared by the website
(site/) and the social slides. Older templates (the carousel template, brand/photo-system) still
read the --ax-* names, so tokens.css maps each of those names onto the current system value.
Edit system.css, then run:  python3 scripts/build-tokens.py
"""

import json
import re
from pathlib import Path

BRAND = Path(__file__).resolve().parent.parent / "brand"
SYSTEM = BRAND / "system.css"

# legacy --ax-* name -> system.css token it now follows
LEGACY = {
    "indigo": "indigo",
    "indigo-deep": "indigo-ink",
    "indigo-soft": "indigo-mist",
    "indigo-app": "indigo-app",
    "indigo-ink": "indigo-ink",
    "cyan": "cyan",
    "cyan-soft": "cyan-mist",
    "ink": "ink",
    "muted": "ink-quiet",
    "canvas": "paper",
    "line": "line",
    "white": "card",
    "amber": "ask",
    "amber-soft": "ask-mist",
    "font-display": "display",
    "font-body": "body",
    "font-serif": "serif",
    "shadow": "shadow",
    "indigo-quiet": "indigo-quiet",
    "on-indigo": "on-indigo",
    "on-indigo-soft": "on-indigo-soft",
    "ok": "ok",
    "ok-soft": "ok-mist",
    "scrim": "scrim",
    "scrim-soft": "scrim-soft",
    "cyan-halo": "cyan-halo",
    "rim": "rim",
}
# legacy names with no system equivalent keep their value (used by a few old templates)
LEGACY_FIXED = {
    "navy-night": "#111B43",
    "grey": "#8A92A6",
    "grey-soft": "#EEF1F6",
    "radius": "24px",
}

# grouping for tokens.json and the kit page
GROUPS = {
    "brand": ["indigo", "indigo-ink", "indigo-app", "indigo-quiet", "cyan"],
    "surface": ["paper", "paper-warm", "card", "indigo-mist", "cyan-mist", "sage-mist", "blush-mist"],
    "ink": ["ink", "ink-soft", "ink-quiet", "line", "line-warm"],
    "status": ["ok", "ok-mist", "ask", "ask-mist"],
    "onDark": ["on-indigo", "on-indigo-soft", "on-dark-soft", "on-dark-line", "on-dark-fill", "rim"],
    "effect": ["scrim", "scrim-soft", "cyan-halo", "cyan-glow", "shadow"],
    "motion": ["ease-out", "ease-in-out", "dur-press", "dur-ui", "dur-swap", "dur-scene"],
    "font": ["serif", "display", "body", "mono"],
}


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(p.capitalize() for p in rest)


def read_tokens() -> dict[str, str]:
    root = re.search(r":root\s*\{(.*?)\n\}", SYSTEM.read_text(), re.S).group(1)
    return {m[0]: " ".join(m[1].split()) for m in re.findall(r"--([a-z0-9-]+):\s*([^;]+);", root)}


def main() -> None:
    t = read_tokens()
    missing = [s for s in LEGACY.values() if s not in t] + [n for g in GROUPS.values() for n in g if n not in t]
    if missing:
        raise SystemExit(f"system.css is missing tokens: {sorted(set(missing))}")

    css = [
        "/* GENERATED by scripts/build-tokens.py from brand/system.css. Do not edit by hand. */",
        "/* Legacy --ax-* names for older templates. New work links brand/system.css directly. */",
        '@import url("https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700'
        '&family=Instrument+Sans:wght@500;600;700&family=Instrument+Serif:ital@0;1&display=swap");',
        ":root {",
    ]
    css += [f"  --ax-{k}: {t[v]};  /* = --{v} */" for k, v in LEGACY.items()]
    css += [f"  --ax-{k}: {v};  /* legacy, no system equivalent */" for k, v in LEGACY_FIXED.items()]
    css.append("}")
    (BRAND / "tokens.css").write_text("\n".join(css) + "\n")

    data = {
        "$comment": "GENERATED by scripts/build-tokens.py from brand/system.css. Do not edit by hand.",
        **{g: {camel(n): t[n] for n in names} for g, names in GROUPS.items()},
        "legacyAliases": {f"--ax-{k}": f"--{v}" for k, v in LEGACY.items()},
    }
    (BRAND / "tokens.json").write_text(json.dumps(data, indent=2) + "\n")
    print(f"tokens.css + tokens.json written from {len(t)} system tokens")


if __name__ == "__main__":
    main()
